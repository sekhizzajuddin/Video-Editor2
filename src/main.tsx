import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import { BrowserRouter } from 'react-router'
import { registerSW } from 'virtual:pwa-register'
import './index.css'
import App from './App.tsx'
import { applyTheme, getInitialTheme } from '@/utils/theme'

// Ensure the theme class is set before the app renders (the inline script in
// index.html already handles the first paint; this is a belt-and-braces call).
applyTheme(getInitialTheme());

createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <BrowserRouter>
      <App />
    </BrowserRouter>
  </StrictMode>,
)

// Offline-first service worker (generated by vite-plugin-pwa at build time).
// Registered only in production builds; the dev server stays SW-free so hot
// reloading is never hijacked by a stale cache.
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  const updateSW = registerSW({
    onOfflineReady() {
      (window as any).__procutOfflineReady = true;
      window.dispatchEvent(new CustomEvent('pwa-offline-ready'));
    },
    onNeedRefresh() {
      (window as any).__procutUpdateReady = true;
      window.dispatchEvent(new CustomEvent('pwa-update-ready'));
    },
    onRegisterError(err) {
      console.error('[PWA] Service worker registration failed:', err);
    },
  });

  // Exposed so the mobile UI's "update available" toast can trigger the reload.
  (window as any).__procutUpdateSW = updateSW;
}
